#!/usr/bin/env python3
"""Generate iso639.h (ISO 639-2 T and B codes -> ISO 639-1, for MP4 audio/subtitle language tags) and
installer/oppo-dv-mkv-languages.txt (the user's language list: explanation + every code the menus know).
The player's menus look file languages up by their 2-letter code (bdpprog, 10-byte table entries); the
overrides make this table give exactly the codes that table holds (it keeps 'iw' for Hebrew, knows
bh/mo/sr/hr for bih/mol/scc/scr, and has no hbs/xho).
usage: nix shell --impure --expr 'with import <nixpkgs> {}; python3.withPackages (p: [p.pycountry])' -c python3 gen_iso639.py"""
import os, pycountry
ent = {}
for l in pycountry.languages:
    a2 = getattr(l, 'alpha_2', None)
    if not a2: continue
    ent[l.alpha_3] = a2
    if getattr(l, 'bibliographic', None): ent[l.bibliographic] = a2
ent.update({'heb': 'iw', 'bih': 'bh', 'mol': 'mo', 'scc': 'sr', 'scr': 'hr'})
for k in ('hbs', 'xho'): ent.pop(k, None)
enc = lambda s: ((ord(s[0]) - 96) << 10) | ((ord(s[1]) - 96) << 5) | (ord(s[2]) - 96)
rows = sorted((enc(k), v) for k, v in ent.items())
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'iso639.h'), 'w') as f:
    f.write('/* ISO 639-2 (T and B) -> ISO 639-1. Generated by gen_iso639.py, sorted by key.\n')
    f.write(' * word = key << 16 | a2; key = 3 letters, 5 bits each (letter - 0x60), as packed in the MP4 mdhd box;\n')
    f.write(' * a2 = first letter << 8 | second letter. */\n')
    f.write('#define ISO639_N %d\n' % len(rows))
    f.write('static const unsigned int iso639[ISO639_N] = {\n')
    for i in range(0, len(rows), 6):
        f.write('    ' + ' '.join('0x%08x,' % (k << 16 | ord(v[0]) << 8 | ord(v[1])) for k, v in rows[i:i + 6]) + '\n')
    f.write('};\n')
print(len(rows), 'entries')

names = {}
for l in pycountry.languages:
    a2 = getattr(l, 'alpha_2', None)
    if a2: names[a2] = l.name
names.update({'iw': names.get('he', 'Hebrew'), 'bh': 'Bihari', 'mo': 'Moldavian', 'sr': names.get('sr', 'Serbian'), 'hr': names.get('hr', 'Croatian')})
by2 = {}
for k, v in ent.items(): by2.setdefault(v, []).append(k)
HEAD = """# oppo-dv-mkv: audio and subtitle languages for MP4 files
#
# The player can use at most 8 audio tracks and 8 subtitle tracks of a file. Most MP4 files have fewer, and then
# this list changes nothing. When a file has more (multi-language files can carry 40 subtitle tracks), the
# player keeps the first 8 in the file and never shows the others.
#
# Write your languages below, one per line, most wanted first (up to 8). The 8 tracks are then chosen like this:
#   1. audio only: the file's default audio track always stays (it is usually the original language);
#   2. every track in the first language of your list (normal, SDH, forced ...), then the second language, and so on;
#   3. the slots still free are filled with the other tracks, in file order, except subtitle tracks of other
#      languages that only have a few lines (forced-only tracks): they would slow down seeking and chapter skips.
# The menus list the tracks in file order, not in the order of this list.
#
# Use the 2-letter or the 3-letter code from the table below, in upper or lower case, for example:
#   EN
#   PT
# Lines starting with # are ignored. With no language listed, the player keeps its own choice (the first 8 tracks).
# After editing, put this file next to the AutoScript folder on the USB stick and run the installer again.
#
# Your languages (one per line, below this comment):

#
# Codes the player's menus know:  2-letter  3-letter  language
"""
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'installer')
with open(os.path.join(root, 'oppo-dv-mkv-languages.txt'), 'w', newline='\r\n') as f:
    f.write(HEAD)
    for a2 in sorted(by2):
        f.write('#   %-3s %-8s %s\n' % (a2.upper(), ' '.join(sorted(x.upper() for x in by2[a2])), names.get(a2, '')))
print('languages.txt:', len(by2), 'languages')
